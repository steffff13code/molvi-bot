# Ключи для кнопок верхнего уровня меню (между «plain» и «Шаблоны»)
# Порядок: Самари → Ключевые моменты → Роадмап → Список задач
TOP_LEVEL_KEYS: list[str] = ["summary", "keypoints", "roadmap", "tasks"]

# Ключи для подменю «Шаблоны» (protocol убран из UI, остался только для статистики)
TEMPLATE_KEYS: list[str] = ["call", "lecture", "legal", "hr", "interview", "note", "therapy"]


def build_summary_prompt(key: str) -> tuple[str, str]:
    """Возвращает (system, user_prefix) для GigaChat по ключу шаблона.

    system = ОБЩИЕ ПРАВИЛА (первыми) + промпт конкретного сценария.
    """
    tmpl = TEMPLATES.get(key) or TEMPLATES["plain"]
    system = f"{COMMON_RULE}\n\n{tmpl.instruction}"
    return system, "Расшифровка:\n"
