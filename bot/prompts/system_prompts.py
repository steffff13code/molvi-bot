@dataclass(frozen=True)
class Template:
    key: str
    label: str        # текст кнопки
    instruction: str  # тело промпта (без расшифровки)


_TEMPLATES: list[Template] = [
    # ── Базовый режим ──────────────────────────────────────────────────────────
    Template(key="plain", label="🎙 Просто расшифровка", instruction=_PLAIN),

    # ── Быстрые форматы (верхний уровень меню) ────────────────────────────────
    Template(key="summary", label="📝 Самари", instruction=_SUMMARY),
    Template(key="keypoints", label="💡 Ключевые моменты", instruction=_KEYPOINTS),
    Template(key="roadmap", label="🗺 Роадмап (план действий)", instruction=_ROADMAP),
    Template(key="tasks", label="✅ Список задач", instruction=_TASKS),

    # ── Тематические шаблоны (подменю «Шаблоны») ─────────────────────────────
    Template(key="call", label="📞 Звонок / переговоры", instruction=_CALL),
    Template(key="lecture", label="🎓 Конспект лекции", instruction=_LECTURE),
    Template(key="legal", label="⚖️ Юридическая консультация", instruction=_LEGAL),
    Template(key="hr", label="🧑‍💼 Собеседование (HR)", instruction=_HR),
    Template(key="interview", label="🎙 Интервью", instruction=_INTERVIEW),
    Template(key="note", label="🧠 Личная заметка", instruction=_NOTE),
    Template(key="therapy", label="💬 Сессия с психологом", instruction=_THERAPY),

    # ── Только для backwards-совместимости статистики (не показывается в меню) ─
    Template(key="protocol", label="📋 Протокол встречи", instruction=_PROTOCOL),
]

TEMPLATES: dict[str, Template] = {t.key: t for t in _TEMPLATES}

# Ключи для кнопок верхнего уровня меню (между «plain» и «Шаблоны»)
# Порядок: Самари → Ключевые моменты → Роадмап → Список задач
TOP_LEVEL_KEYS: list[str] = ["summary", "keypoints", "roadmap", "tasks"]

# Ключи для подменю «Шаблоны» (protocol убран из UI, остался только для статистики)
TEMPLATE_KEYS: list[str] = ["call", "lecture", "legal", "hr", "interview", "note", "therapy"]


def build_summary_prompt(key: str) -> tuple[str, str]:
    """Возвращает (system, user_prefix) для GigaChat по ключу шаблона.

    system = ОБЩИЕ ПРАВИЛА (первыми) + промпт конкретного сценария с примером.
    """
    tmpl = TEMPLATES.get(key) or TEMPLATES["plain"]
    system = f"{COMMON_RULE}\n\n{tmpl.instruction}"
    return system, "Расшифровка:\n"
